@router.get("/{config}/stream/{type}/{id}.json")
async def stream(
    request: Request,
    config: str,
    type: str,
    id: str,
):
    logger.info("")
    logger.info(
        "========================================"
    )
    logger.info(
        "=== CAULDRON STREAM REQUEST ==="
    )
    logger.info(
        "TYPE: %s",
        type,
    )
    logger.info(
        "ID: %s",
        id,
    )
    logger.info(
        "CONFIG: %s",
        config,
    )
    logger.info(
        "========================================"
    )

    # -----------------------------------------------------
    # MEDIA TYPE
    # -----------------------------------------------------

    if type not in (
        "movie",
        "series",
    ):
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported media type: {type}",
        )

    # -----------------------------------------------------
    # MEDIA
    # -----------------------------------------------------

    media = await resolve_media(
        type,
        id,
    )

    logger.info(
        "SEARCHING: %s (%s) S%sE%s",
        media["title"],
        media["imdb_id"],
        media["season"],
        media["episode"],
    )

    # -----------------------------------------------------
    # CONFIG
    # -----------------------------------------------------

    cfg = _decode_config(config)

    provider_str, api_key = (
        _normalize_debrid_config(cfg)
    )

    debrid_client = None

    if provider_str and api_key:
        try:
            provider = DebridProvider(
                provider_str
            )

            debrid_client = (
                get_debrid_client(
                    provider,
                    api_key,
                )
            )

            logger.info(
                "Using debrid provider: %s",
                provider_str,
            )

        except Exception as exc:
            logger.warning(
                "Unable to initialize debrid "
                "provider %s: %s",
                provider_str,
                exc,
            )

    else:
        logger.info(
            "No debrid credentials configured"
        )

    # -----------------------------------------------------
    # SEARCH
    # -----------------------------------------------------

    try:
        results = await search_all(
            media["title"],
            imdb_id=media["imdb_id"],
            season=media["season"],
            episode=media["episode"],
            media_type=media["type"],
        )

    except Exception as exc:
        logger.exception(
            "Search failed"
        )

        raise HTTPException(
            status_code=500,
            detail=f"Search failed: {exc}",
        )

    logger.info(
        "SEARCH RESULTS: %d",
        len(results),
    )

    if not results:
        logger.info(
            "NO RESULTS"
        )

        return {
            "streams": []
        }

    # -----------------------------------------------------
    # CACHE CHECK
    # -----------------------------------------------------

    cache_status_map = {}

    if debrid_client:
        try:
            info_hashes = [
                str(
                    t.info_hash
                ).lower()
                for t in results
                if getattr(
                    t,
                    "info_hash",
                    None,
                )
            ]

            logger.info(
                "Checking %s cache status "
                "for %d hashes",
                provider_str,
                len(info_hashes),
            )

            if info_hashes:
                cache_status_map = (
                    await debrid_client.check_cache(
                        info_hashes
                    )
                )

                cached_count = sum(
                    1
                    for status
                    in cache_status_map.values()
                    if status
                    == CacheStatus.CACHED
                )

                uncached_count = sum(
                    1
                    for status
                    in cache_status_map.values()
                    if status
                    == CacheStatus.NOT_CACHED
                )

                unknown_count = (
                    len(info_hashes)
                    - cached_count
                    - uncached_count
                )

                logger.info(
                    "CACHE RESULTS: "
                    "%d cached / "
                    "%d uncached / "
                    "%d unknown / "
                    "%d total",
                    cached_count,
                    uncached_count,
                    unknown_count,
                    len(info_hashes),
                )

                for torrent in results:
                    info_hash = str(
                        getattr(
                            torrent,
                            "info_hash",
                            "",
                        )
                    ).lower()

                    status = (
                        cache_status_map.get(
                            info_hash,
                            CacheStatus.UNKNOWN,
                        )
                    )

                    logger.info(
                        "CACHE: %-12s | %s",
                        _cache_status_label(
                            status
                        ),
                        getattr(
                            torrent,
                            "title",
                            "unknown",
                        ),
                    )

        except Exception as exc:
            logger.exception(
                "Cache check failed: %s",
                exc,
            )

    # -----------------------------------------------------
    # EPISODE FILTERING
    # -----------------------------------------------------

    if (
        media["type"] == "series"
        and media["season"] is not None
        and media["episode"] is not None
    ):
        season = int(
            media["season"]
        )

        episode = int(
            media["episode"]
        )

        patterns = [
            f"s{season:02d}e{episode:02d}",
            f"s{season}e{episode}",
            f"{season}x{episode:02d}",
        ]

        filtered = []

        for torrent in results:
            torrent_title = str(
                getattr(
                    torrent,
                    "title",
                    "",
                )
            ).lower()

            if any(
                pattern.lower()
                in torrent_title
                for pattern in patterns
            ):
                filtered.append(
                    torrent
                )

        results = filtered

        logger.info(
            "AFTER EPISODE FILTER: %d",
            len(results),
        )

    # -----------------------------------------------------
    # CACHED ONLY
    # -----------------------------------------------------

    cached_only = cfg.get(
        "cached_only",
        False,
    )

    if (
        cached_only
        and debrid_client
    ):
        results = [
            torrent
            for torrent in results
            if cache_status_map.get(
                str(
                    torrent.info_hash
                ).lower(),
                CacheStatus.UNKNOWN,
            )
            == CacheStatus.CACHED
        ]

        logger.info(
            "AFTER CACHED-ONLY FILTER: %d",
            len(results),
        )

    # -----------------------------------------------------
    # FILTERING
    # -----------------------------------------------------

    try:
        from app.filtering.pipeline import (
            FilterPipeline
        )

        logger.info(
            "FILTER CONFIG - required_languages: %s",
            cfg.get("required_languages", [])
        )
        logger.info(
            "FILTER CONFIG - excluded_languages: %s",
            cfg.get("excluded_languages", [])
        )
        logger.info(
            "FILTER CONFIG - language: %s",
            cfg.get("language", [])
        )

        pipeline = FilterPipeline(
            cfg
        )

        results = pipeline.apply(
            results
        )

        logger.info(
            "AFTER FILTER PIPELINE: %d",
            len(results),
        )

    except Exception:
        logger.exception(
            "Filtering pipeline failed"
        )

    # -----------------------------------------------------
    # SORTING
    # -----------------------------------------------------

    try:
        from app.filtering.sorting import (
            sort_torrents
        )

        sort_criteria = cfg.get(
            "sort_criteria"
        )

        if isinstance(
            sort_criteria,
            str,
        ):
            sort_criteria = [
                value.strip()
                for value
                in sort_criteria.split(",")
                if value.strip()
            ]

        if not sort_criteria:
            sort_criteria = [
                "cached",
                "seeders",
                "resolution",
                "quality",
            ]

        sort_order = cfg.get(
            "sort_order",
            "desc",
        )

        allow_season_packs = (
            cfg.get(
                "allow_season_packs",
                False,
            )
        )

        results = sort_torrents(
            results,
            sort_criteria=sort_criteria,
            sort_order=sort_order,
            allow_season_packs=(
                allow_season_packs
            ),
            cache_status_map=(
                cache_status_map
            ),
        )

        logger.info(
            "AFTER SORTING: %d "
            "using %s %s",
            len(results),
            sort_criteria,
            sort_order,
        )

    except Exception:
        logger.exception(
            "Sorting failed"
        )

    # -----------------------------------------------------
    # BUILD STREAMS
    # -----------------------------------------------------

    streams = []

    base_url = _external_base_url(
        request
    )

    logger.info(
        "External base URL: %s",
        base_url,
    )

    for torrent in results:
        try:
            info_hash = str(
                getattr(
                    torrent,
                    "info_hash",
                    "",
                )
            ).lower()

            if not info_hash:
                logger.warning(
                    "Skipping torrent without "
                    "info hash: %s",
                    getattr(
                        torrent,
                        "title",
                        "unknown",
                    ),
                )

                continue

            cache_status = (
                cache_status_map.get(
                    info_hash,
                    CacheStatus.UNKNOWN,
                )
            )

            cache_label = (
                _cache_status_label(
                    cache_status
                )
            )

            quality = getattr(
                torrent,
                "quality",
                None,
            )

            indexer = getattr(
                torrent,
                "indexer",
                None,
            )

            seeders = getattr(
                torrent,
                "seeders",
                None,
            )

            size_bytes = getattr(
                torrent,
                "size_bytes",
                None,
            )

            # -------------------------------------------------
            # STREAM NAME
            # -------------------------------------------------

            name_parts = [
                "🧙 Cauldron"
            ]

            if indexer:
                name_parts.append(
                    str(indexer)
                )

            if quality:
                name_parts.append(
                    str(quality)
                )

            if debrid_client:
                name_parts.append(
                    cache_label
                )
            else:
                name_parts.append(
                    "P2P"
                )

            stream_name = (
                " • ".join(
                    name_parts
                )
            )

            # -------------------------------------------------
            # STREAM TITLE
            # -------------------------------------------------

            title_parts = [
                str(
                    getattr(
                        torrent,
                        "title",
                        "Unknown",
                    )
                )
            ]

            if quality:
                title_parts.append(
                    f"Quality: {quality}"
                )

            if seeders is not None:
                title_parts.append(
                    f"Seeds: {seeders}"
                )

            if size_bytes:
                try:
                    size_gb = (
                        float(size_bytes)
                        / (1024 ** 3)
                    )

                    if size_gb >= 1:
                        title_parts.append(
                            f"Size: "
                            f"{size_gb:.2f} GB"
                        )

                    else:
                        size_mb = (
                            float(size_bytes)
                            / (1024 ** 2)
                        )

                        title_parts.append(
                            f"Size: "
                            f"{size_mb:.0f} MB"
                        )

                except (
                    TypeError,
                    ValueError,
                ):
                    pass

            if debrid_client:
                title_parts.append(
                    f"Cache: {cache_label}"
                )

            # -------------------------------------------------
            # PLAYBACK URL
            # -------------------------------------------------

            if debrid_client:
                stream_url = (
                    f"{base_url}/"
                    f"{config}/playback/"
                    f"{info_hash}"
                )

                stream_data = {
                    "name": stream_name,
                    "title": "\n".join(
                        title_parts
                    ),
                    "url": stream_url,
                    "behaviorHints": {
                        "bingeGroup": (
                            "cauldron"
                        ),
                    },
                }

                logger.info(
                    "PLAYBACK URL: %s",
                    stream_url,
                )

            else:
                magnet = getattr(
                    torrent,
                    "magnet",
                    None,
                )

                stream_data = {
                    "name": stream_name,
                    "title": "\n".join(
                        title_parts
                    ),
                    "infoHash": info_hash,
                    "sources": (
                        [magnet]
                        if magnet
                        else []
                    ),
                    "behaviorHints": {
                        "bingeGroup": (
                            "cauldron"
                        ),
                    },
                }

            streams.append(
                stream_data
            )

            logger.info(
                "STREAM: %-30s | %s",
                stream_name,
                getattr(
                    torrent,
                    "title",
                    "unknown",
                ),
            )

        except Exception as exc:
            logger.exception(
                "Failed converting torrent "
                "to stream: %s",
                exc,
            )

    logger.info(
        "RETURNING STREAMS: %d",
        len(streams),
    )

    return {
        "streams": streams
    }


