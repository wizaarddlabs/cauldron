@router.get("/{config}/stream/{type}/{id}.json")
async def stream(
    request: Request,
    config: str,
    type: str,
    id: str,
):
    logger.info(
        "Stream request: type=%s id=%s config=%s",
        type,
        id,
        mask_config_id(config),
    )

    # -----------------------------------------------------
    # MEDIA TYPE
    # -----------------------------------------------------

    if type not in (
        "movie",
        "series",
    ):
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported media type: {type}",
        )

    # -----------------------------------------------------
    # MEDIA
    # -----------------------------------------------------

    media = await resolve_media(
        type,
        id,
    )

    logger.info(
        "SEARCHING: %s (%s) S%sE%s",
        media["title"],
        media["imdb_id"],
        media["season"],
        media["episode"],
    )

    # -----------------------------------------------------
    # CONFIG
    # -----------------------------------------------------

    cfg = _decode_config(config)

    accounts: list[DebridAccount] = []

    for provider_str, api_key in _configured_accounts(cfg):
        try:
            client = get_debrid_client(
                DebridProvider(provider_str),
                api_key,
            )
        except Exception as exc:
            logger.warning(
                "Unable to initialize debrid provider %s: %s",
                provider_str,
                redact_value(exc, api_key),
            )
            continue

        accounts.append(
            DebridAccount(provider_str, api_key, client)
        )

    if accounts:
        logger.info(
            "Using debrid providers: %s",
            ", ".join(account.provider for account in accounts),
        )
    else:
        logger.info(
            "No debrid credentials configured"
        )

    torrin_account = next(
        (account for account in accounts if account.provider == "torrin"),
        None,
    )

    stream_mode = cfg.get("stream_mode")
    if stream_mode not in STREAM_MODES:
        stream_mode = STREAM_MODE_BEST

    # -----------------------------------------------------
    # SEARCH
    # -----------------------------------------------------

    try:
        results = await search_all(
            media["title"],
            imdb_id=media["imdb_id"],
            season=media["season"],
            episode=media["episode"],
            media_type=media["type"],
            # Used to recognise localized (e.g. Spanish-titled) releases.
            year=media.get("year"),
            aliases=media.get("aliases"),
            # Only Torrin offers an account-history search.
            account_provider=(
                "torrin" if torrin_account else None
            ),
            account_api_key=(
                torrin_account.api_key if torrin_account else None
            ),
        )

    except Exception as exc:
        logger.exception(
            "Search failed"
        )

        raise HTTPException(
            status_code=500,
            detail=f"Search failed: {exc}",
        ) from exc

    logger.info(
        "SEARCH RESULTS: %d",
        len(results),
    )

    if not results:
        logger.info(
            "NO RESULTS"
        )

        return {
            "streams": []
        }

    # Narrow series results before asking the debrid provider about cache
    # availability. This avoids sending hashes for unrelated episodes.
    if (
        media["type"] == "series"
        and media["season"] is not None
        and media["episode"] is not None
    ):
        season = int(media["season"])
        episode = int(media["episode"])
        patterns = [
            f"s{season:02d}e{episode:02d}",
            f"s{season}e{episode}",
            f"{season}x{episode:02d}",
        ]

        results = [
            torrent
            for torrent in results
            if any(
                pattern in str(getattr(torrent, "title", "")).lower()
                for pattern in patterns
            )
        ]

        logger.info(
            "AFTER EPISODE FILTER: %d",
            len(results),
        )

        if not results:
            return {"streams": []}

    # -----------------------------------------------------
    # CACHE CHECK
    # -----------------------------------------------------

    cache_status_map = {}
    provider_cache_maps: dict[str, dict] = {}

    if accounts:
        info_hashes = [
            str(t.info_hash).lower()
            for t in results
            if getattr(t, "info_hash", None)
        ]

        logger.info(
            "Checking cache on %s for %d hashes",
            ", ".join(account.provider for account in accounts),
            len(info_hashes),
        )

        provider_cache_maps = await check_all_caches(
            accounts,
            info_hashes,
        )

        # Completed Torrin account jobs are playable for this user
        # even when they are not in Torrin's shared cache index.
        if torrin_account:
            _mark_torrin_account_results_cached(
                provider_cache_maps.setdefault("torrin", {}),
                results,
            )
            results = _prioritize_torrin_account_results(results)

        cache_status_map = combine_cache_status(
            provider_cache_maps,
            info_hashes,
        )

        for account in accounts:
            statuses = provider_cache_maps.get(account.provider, {}).values()
            logger.info(
                "CACHE RESULTS %s: %d cached / %d uncached / %d total",
                account.provider,
                sum(1 for status in statuses if status == CacheStatus.CACHED),
                sum(1 for status in statuses if status == CacheStatus.NOT_CACHED),
                len(info_hashes),
            )

        for torrent in results:
            logger.debug(
                "CACHE: %-12s | %s",
                cache_status_label(
                    cache_status_map.get(
                        str(getattr(torrent, "info_hash", "")).lower(),
                        CacheStatus.UNKNOWN,
                    )
                ),
                getattr(torrent, "title", "unknown"),
            )

    # -----------------------------------------------------
    # CACHED ONLY
    # -----------------------------------------------------

    cached_only = cfg.get(
        "cached_only",
        False,
    )

    if (
        cached_only
        and accounts
    ):
        results = [
            torrent
            for torrent in results
            if cache_status_map.get(
                str(
                    torrent.info_hash
                ).lower(),
                CacheStatus.UNKNOWN,
            )
            == CacheStatus.CACHED
        ]

        logger.info(
            "AFTER CACHED-ONLY FILTER: %d",
            len(results),
        )

    # -----------------------------------------------------
    # FILTERING
    # -----------------------------------------------------

    results = _apply_configured_filters(
        results,
        cfg,
    )

    logger.info(
        "AFTER FILTER PIPELINE: %d",
        len(results),
    )

    # -----------------------------------------------------
    # SORTING
    # -----------------------------------------------------

    try:
        from app.filtering.sorting import sort_torrents

        sort_criteria = cfg.get(
            "sort_criteria"
        )

        if isinstance(
            sort_criteria,
            str,
        ):
            sort_criteria = [
                value.strip()
                for value
                in sort_criteria.split(",")
                if value.strip()
            ]

        if not sort_criteria:
            sort_criteria = [
                "cached",
                "seeders",
                "resolution",
                "quality",
            ]

        sort_order = cfg.get(
            "sort_order",
            "desc",
        )

        allow_season_packs = (
            cfg.get(
                "allow_season_packs",
                False,
            )
        )

        results = sort_torrents(
            results,
            sort_criteria=sort_criteria,
            sort_order=sort_order,
            allow_season_packs=(
                allow_season_packs
            ),
            cache_status_map=(
                cache_status_map
            ),
        )

        logger.info(
            "AFTER SORTING: %d "
            "using %s %s",
            len(results),
            sort_criteria,
            sort_order,
        )

    except Exception:
        logger.exception(
            "Sorting failed"
        )

    # -----------------------------------------------------
    # BUILD STREAMS
    # -----------------------------------------------------

    streams = []

    base_url = _external_base_url(
        request
    )

    logger.debug(
        "External base URL: %s",
        base_url,
    )

    # Name the provider on each stream only when there is a choice.
    show_provider = len(accounts) > 1

    for torrent in results:
        info_hash = str(getattr(torrent, "info_hash", "")).lower()

        targets: list[DebridAccount | None] = accounts_for_torrent(
            info_hash,
            accounts,
            provider_cache_maps,
            stream_mode,
        ) or [None]

        for account in targets:
            provider_map = (
                provider_cache_maps.get(account.provider, {})
                if account
                else cache_status_map
            )

            # In "one stream per provider" mode, cached-only also drops the
            # providers that don't have this torrent cached.
            if (
                account
                and cached_only
                and provider_map.get(info_hash) != CacheStatus.CACHED
            ):
                continue

            try:
                stream_data = build_stream(
                    torrent,
                    cache_status_map=provider_map,
                    has_debrid=account is not None,
                    base_url=base_url,
                    config=config,
                    provider=account.provider if account else None,
                    provider_label=(
                        account.label if account and show_provider else None
                    ),
                )
            except Exception:
                logger.exception("Failed converting torrent to stream")
                continue

            if stream_data is not None:
                streams.append(stream_data)
                logger.debug(
                    "Stream: %-30s | %s",
                    stream_data["name"],
                    getattr(torrent, "title", "unknown"),
                )

    logger.info(
        "RETURNING STREAMS: %d",
        len(streams),
    )

    return {
        "streams": streams
    }


