@router.api_route(
    "/{config}/playback/{info_hash}",
    methods=["GET", "HEAD"],
)
async def playback(
    request: Request,
    config: str,
    info_hash: str,
):
    """
    Resolve a torrent hash through the configured
    debrid provider and redirect to its actual
    playback URL.

    HEAD requests are handled as lightweight
    availability checks and do not trigger
    debrid resolution.

    GET requests use an in-memory cache and per-hash
    locking to prevent duplicate debrid transfers.
    """

    logger.info("")
    logger.info(
        "========================================"
    )
    logger.info(
        "=== CAULDRON PLAYBACK REQUEST ==="
    )
    logger.info(
        "METHOD: %s",
        request.method,
    )
    logger.info(
        "CONFIG: %s",
        config,
    )
    logger.info(
        "HASH: %s",
        info_hash,
    )
    logger.info(
        "========================================"
    )

    # -----------------------------------------------------
    # LOAD CONFIG
    # -----------------------------------------------------

    cfg = _decode_config(
        config
    )

    provider_str, api_key = (
        _normalize_debrid_config(
            cfg
        )
    )

    if not provider_str:
        raise HTTPException(
            status_code=400,
            detail=(
                "No debrid provider "
                "configured"
            ),
        )

    if not api_key:
        raise HTTPException(
            status_code=400,
            detail=(
                "No debrid API key "
                "configured"
            ),
        )

    # -----------------------------------------------------
    # NORMALIZE HASH
    # -----------------------------------------------------

    info_hash = (
        info_hash
        .strip()
        .lower()
        .replace(
            "urn:btih:",
            "",
        )
    )

    if not info_hash:
        raise HTTPException(
            status_code=400,
            detail="Invalid torrent hash",
        )

    # -----------------------------------------------------
    # HEAD REQUEST
    # -----------------------------------------------------
    #
    # Stremio/proxies can issue HEAD before GET.
    #
    # Do NOT create a transfer here.
    # -----------------------------------------------------

    if request.method == "HEAD":
        logger.info(
            "HEAD playback check accepted"
        )

        return Response(
            status_code=200
        )

    # -----------------------------------------------------
    # PLAYBACK CACHE KEY
    # -----------------------------------------------------
    #
    # Include provider and config so different users
    # cannot accidentally share a cached URL.
    # -----------------------------------------------------

    cache_key = (
        f"{config}:"
        f"{provider_str}:"
        f"{info_hash}"
    )

    # -----------------------------------------------------
    # CHECK CACHE
    # -----------------------------------------------------

    cached_url = _get_cached_playback_url(
        cache_key
    )

    if cached_url:
        logger.info(
            "PLAYBACK CACHE HIT"
        )

        logger.info(
            "Provider: %s",
            provider_str,
        )

        logger.info(
            "Hash: %s",
            info_hash,
        )

        return RedirectResponse(
            url=cached_url,
            status_code=302,
        )

    logger.info(
        "PLAYBACK CACHE MISS"
    )

    # -----------------------------------------------------
    # PER-HASH LOCK
    # -----------------------------------------------------
    #
    # This is important when Stremio sends several GETs
    # at almost exactly the same time.
    #
    # Only the first request will contact Premiumize.
    # The others wait and then use the newly cached URL.
    # -----------------------------------------------------

    playback_lock = await _get_playback_lock(
        cache_key
    )

    async with playback_lock:

        # -------------------------------------------------
        # CHECK CACHE AGAIN
        # -------------------------------------------------
        #
        # Another request may have populated the cache
        # while we were waiting for the lock.
        # -------------------------------------------------

        cached_url = _get_cached_playback_url(
            cache_key
        )

        if cached_url:
            logger.info(
                "PLAYBACK CACHE HIT AFTER LOCK"
            )

            return RedirectResponse(
                url=cached_url,
                status_code=302,
            )

        # -------------------------------------------------
        # PROVIDER
        # -------------------------------------------------

        try:
            provider = DebridProvider(
                provider_str
            )

            debrid_client = (
                get_debrid_client(
                    provider,
                    api_key,
                )
            )

        except Exception as exc:
            logger.exception(
                "Unable to initialize "
                "debrid provider"
            )

            raise HTTPException(
                status_code=500,
                detail=(
                    f"Unable to initialize "
                    f"debrid provider: {exc}"
                ),
            )

        # -------------------------------------------------
        # MAGNET
        # -------------------------------------------------

        magnet = (
            f"magnet:?xt=urn:btih:"
            f"{info_hash}"
        )

        logger.info(
            "Resolving magnet: %s",
            magnet,
        )

        # -------------------------------------------------
        # ADD MAGNET
        # -------------------------------------------------

        try:
            torrent_id = (
                await debrid_client.add_magnet(
                    magnet
                )
            )

            logger.info(
                "Provider torrent ID: %s",
                torrent_id,
            )

        except Exception as exc:
            logger.exception(
                "Failed to add magnet to %s",
                provider_str,
            )

            raise HTTPException(
                status_code=502,
                detail=(
                    f"Failed to add torrent: "
                    f"{exc}"
                ),
            )

        # -------------------------------------------------
        # RESOLVE PLAYBACK
        # -------------------------------------------------

        last_error = None

        for attempt in range(15):
            try:
                resolved = (
                    await debrid_client.get_playback_link(
                        torrent_id
                    )
                )

                playback_url = getattr(
                    resolved,
                    "playback_url",
                    None,
                )

                if playback_url:
                    logger.info(
                        "PLAYBACK RESOLVED"
                    )

                    logger.info(
                        "Provider: %s",
                        provider_str,
                    )

                    logger.info(
                        "File: %s",
                        getattr(
                            resolved,
                            "file_name",
                            "unknown",
                        ),
                    )

                    # -----------------------------------------
                    # CACHE RESOLVED URL
                    # -----------------------------------------

                    _cache_playback_url(
                        cache_key,
                        playback_url,
                    )

                    logger.info(
                        "PLAYBACK URL CACHED "
                        "FOR %d SECONDS",
                        PLAYBACK_CACHE_TTL,
                    )

                    return RedirectResponse(
                        url=playback_url,
                        status_code=302,
                    )

                last_error = (
                    "Provider returned "
                    "no playback URL"
                )

            except Exception as exc:
                last_error = exc

                logger.info(
                    "Playback not ready "
                    "(attempt %d/15): %s",
                    attempt + 1,
                    exc,
                )

            if attempt < 14:
                await asyncio.sleep(2)

        logger.error(
            "Playback resolution failed "
            "after 30 seconds: %s",
            last_error,
        )

        raise HTTPException(
            status_code=504,
            detail=(
                f"Playback was not ready on "
                f"{provider_str}: "
                f"{last_error}"
            ),
        )
