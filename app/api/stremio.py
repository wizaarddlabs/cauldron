def _decode_config(config: str):
    """
    Load the generated Stremio configuration from SQLite.

    The config value in the Stremio URL is the short ID
    generated by app.config_store.save_config().
    """

    cfg = load_config(config)

    if cfg is None:
        logger.error("Configuration not found")

        raise HTTPException(
            status_code=404,
            detail="Configuration not found",
        )

    logger.info(
        "Config provider: %s",
        cfg.get("provider"),
    )

    return cfg


def _normalize_debrid_config(cfg):
    """
    Normalize debrid configuration into:

        (provider, api_key)

    The generated Stremio configuration takes priority.
    """

    configured_provider = cfg.get("provider")

    if configured_provider == "p2p":
        # Explicit choice of direct P2P streams; never fall back to the
        # server-wide Torrin key.
        return None, None

    if configured_provider:
        # A generated config is authoritative. Do not silently replace a
        # missing/invalid key with the server-wide Torrin credential.
        configured_key = cfg.get("api_key")

        if not configured_key:
            configured_key = cfg.get(
                f"{configured_provider}_key"
            )

        return (
            configured_provider,
            configured_key,
        )

    if cfg.get("torbox_key"):
        return (
            "torbox",
            cfg["torbox_key"],
        )

    if cfg.get("realdebrid_key"):
        return (
            "realdebrid",
            cfg["realdebrid_key"],
        )

    if cfg.get("alldebrid_key"):
        return (
            "alldebrid",
            cfg["alldebrid_key"],
        )

    if cfg.get("premiumize_key"):
        return (
            "premiumize",
            cfg["premiumize_key"],
        )

    if cfg.get("torrin_key"):
        return (
            "torrin",
            cfg["torrin_key"],
        )

    # -----------------------------------------------------
    # Application-level Torrin configuration
    # -----------------------------------------------------

    settings = get_settings()

    torrin_key = getattr(
        settings,
        "torrin_api_key",
        None,
    )

    if torrin_key:
        return (
            "torrin",
            torrin_key,
        )

    return None, None


def _configured_accounts(cfg) -> list[tuple[str, str]]:
    """
    All debrid (provider, api_key) pairs for a config, in priority order.

    Configs created since multi-provider support store a ``providers`` list;
    older ones use the single-provider fields via _normalize_debrid_config.
    An empty list means direct P2P streams.
    """

    accounts = accounts_from_config(cfg)

    if accounts is not None:
        return accounts

    provider, api_key = _normalize_debrid_config(cfg)

    if provider and api_key:
        return [(provider, api_key)]

    return []


# =========================================================
# CACHE LABEL
# =========================================================


def _mark_torrin_account_results_cached(
    cache_status_map,
    torrents,
):
    """Mark completed Torrin account jobs as ready for the current user."""
    for torrent in torrents:
        if getattr(torrent, "source", "") == "torrin-account":
            cache_status_map[str(torrent.info_hash).lower()] = CacheStatus.CACHED


def _prioritize_torrin_account_results(torrents):
    """Keep ready Torrin account results ahead of capped public results."""
    return sorted(
        torrents,
        key=lambda torrent: getattr(torrent, "source", "") != "torrin-account",
    )


# =========================================================
# EXTERNAL URL
# =========================================================


def _external_base_url(request: Request) -> str:
    """
    Determine the externally reachable Cauldron URL.

    When Cauldron is behind Nginx Proxy Manager,
    X-Forwarded-Host / X-Forwarded-Proto are used.

    This prevents Stremio from receiving internal URLs
    such as:

        http://localhost:8000/...
    """

    forwarded_host = request.headers.get(
        "x-forwarded-host"
    )

    host = (
        forwarded_host
        or request.headers.get("host")
    )

    forwarded_proto = request.headers.get(
        "x-forwarded-proto"
    )

    proto = (
        forwarded_proto
        or request.url.scheme
    )

    if host:
        host = host.split(",")[0].strip()
        proto = proto.split(",")[0].strip()

        return (
            f"{proto}://{host}"
        ).rstrip("/")

    settings = get_settings()

    return settings.addon_url.rstrip("/")


